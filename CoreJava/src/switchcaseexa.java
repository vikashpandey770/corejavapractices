public class switchcaseexa {
    public static void main(String[] args) {
        int num=10;

        switch (num){
            case 1:
                System.out.println("hello monday");
                break;
            case 2:
                System.out.println("hello tuesday");
                break;
            case 3:
                System.out.println("hello wednesday");
                break;
            default:
                System.out.println("not any day");
        }
    }
}
