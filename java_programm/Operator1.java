public class Operator1 {
    public static void main(String args[]){
        int a=10;
        int b=6+a;
        int c=a*b;
        int d=c-a;
        int e=d/c;
        System.out.println("this is a arithmetic operators");
        System.out.println("a+b="+b);
        System.out.println("a*b="+c);
        System.out.println("c-a="+d);
        System.out.println("d/c"+e);
        int x=25;
        x+=3;
        a+=10;

        System.out.println("this is a assignment operator");
        System.out.println(x);
        System.out.println(a);

        System.out.println("this is a comparision operator");
        System.out.println(5==20);
        System.out.println(10==10);
        System.out.println(64<8);
        System.out.println(10>20);
        System.out.println(10<20);

        System.out.println("this is a logical operator");
        System.out.println(50>10&&60>50);
        System.out.println(10>30&& 10>3);
        System.out.println(10>30||10>4);
        System.out.println(50<10||20>100);





    }
}
